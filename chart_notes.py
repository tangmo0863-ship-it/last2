def note_markdown(key):
    """แปลงคำอธิบายเป็น Markdown (ใช้ทั้งใน Dashboard และส่งออกไปเล่มรายงานได้)"""
    n = CHART_NOTES.get(key)
    if not n:
        return None
    parts = [f"**กราฟนี้แสดง:** {n['what']}", "", "**วิธีอ่าน**"]
    parts += [f"- {x}" for x in n["read"]]
    parts += ["", "**เทคนิค / สูตรที่ใช้**"]
    parts += [f"- {x}" for x in n["technique"]]
    parts += ["", f"**ทำไมใช้วิธีนี้:** {n['why']}"]
    if n.get("refs"):
        parts += ["", "**อ้างอิง:** " + " · ".join(n["refs"])]
    if n.get("limits"):
        parts += ["", f"**ข้อจำกัด:** {n['limits']}"]
    return "\n".join(parts)
